"""Offline, development-time Lucide subset. Not a runtime dependency."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

parser = argparse.ArgumentParser()
parser.add_argument('--package', type=Path, required=True)
parser.add_argument('--font-tools', type=Path, required=True)
args = parser.parse_args()
sys.path.insert(0, str(args.font_tools.resolve()))
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

def require(condition, message):
    if not condition:
        raise SystemExit(message)

require(fontTools.__version__ == '4.67.0', 'Use the pinned FontTools conversion environment')
package = json.loads((args.package / 'package.json').read_text(encoding='utf-8'))
require(package['name'] == 'lucide-static' and package['version'] == '1.58.0', 'Expected pinned Lucide 1.58.0')
source = args.package / 'font/lucide.ttf'
digest = hashlib.sha256(source.read_bytes()).hexdigest()
require(digest == '2c0453c7d2efb9a11f0de70842dfe87c1b7871717f1edb38b9495dfd3a3f31e0', 'Source font hash mismatch')
names = ['orbit', 'info', 'shield-check', 'lock-keyhole', 'unlock-keyhole',
         'arrow-down-to-line', 'arrow-up-from-line']
points = json.loads((args.package / 'font/codepoints.json').read_text(encoding='utf-8'))
points = {name: points[name] for name in names}
root = Path(__file__).resolve().parent.parent
output = root / 'assets/Fonts/lucide-bench.ttf'
font = TTFont(source, recalcTimestamp=False)
options = subset.Options()
options.recalc_timestamp = False
options.name_IDs = ['*']
options.name_legacy = True
options.name_languages = ['*']
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=sorted(points.values()))
subsetter.subset(font)
font.save(output)
check = TTFont(output)
require(set(check.getBestCmap()) == set(points.values()), "Subset must retain exactly the seven public codepoints")
check.close()
font.close()
metadata = {'package': 'lucide-static@1.58.0', 'license': 'ISC',
            'source': 'font/lucide.ttf', 'sourceSha256': digest,
            'fontTools': fontTools.__version__, 'operation': 'Seven-glyph subset; no path redesign',
            'outputSha256': hashlib.sha256(output.read_bytes()).hexdigest(), 'codepoints': points}
(output.with_suffix('.json')).write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
header = '// Generated by tools/generate_icons.py from pinned Lucide 1.58.0. ISC.\n#pragma once\nnamespace lucide {\n'
for name, point in points.items():
    escaped = ''.join(f'\\x{byte:02x}' for byte in chr(point).encode('utf-8'))
    header += f'inline constexpr const char *{name.replace("-", "_")} = "{escaped}";\n'
header += '} // namespace lucide\n'
(root / 'src/lucide_icons.hpp').write_text(header, encoding='utf-8')
print(f'Created {output.name}: {output.stat().st_size} bytes, seven official Lucide glyphs')
